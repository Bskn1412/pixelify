-- Consolidated baseline for the visitor leaderboard schema.
-- Squashes migrations 202611100001..202611100006 into the final state of every
-- object. Idempotent on purpose: safe to apply to a fresh database and to one
-- that already ran the original migrations (create if not exists / replace).
--
-- Layout:
--   1. extensions, tables, indexes, row level security
--   2. functions: page-view tracking, public stats, point awards,
--      leaderboard data (single-arg fallback kept for the API route),
--      period rankings, activity history
--   3. permissions and removal of overloads no longer called by the API

create extension if not exists pgcrypto;

create table if not exists public.users (
  id uuid primary key,
  username text unique,
  display_name text not null default 'Pixelify User',
  avatar_url text,
  country_code text check (country_code is null or country_code ~ '^[A-Z]{2}$'),
  created_at timestamptz not null default now(),
  constraint users_username_length check (username is null or char_length(username) between 3 and 32)
);

create table if not exists public.page_views (
  id bigint generated by default as identity primary key,
  visitor_id uuid not null,
  user_id uuid references public.users(id) on delete set null,
  page_path text not null default '/',
  referrer text not null default '',
  network_hash text,
  created_at timestamptz not null default now()
);

create table if not exists public.leaderboard (
  id bigint generated by default as identity primary key,
  user_id uuid not null unique references public.users(id) on delete cascade,
  score bigint not null default 0 check (score >= 0),
  updated_at timestamptz not null default now()
);

create table if not exists public.score_transactions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.users(id) on delete cascade,
  operation_id uuid not null,
  action text not null check (action in ('background_removal', 'upscale')),
  points smallint not null default 1 check (points = 1),
  created_at timestamptz not null default now(),
  unique (user_id, operation_id)
);

create index if not exists page_views_visitor_created_idx
  on public.page_views (visitor_id, created_at desc);
create index if not exists page_views_created_idx
  on public.page_views (created_at desc);
create index if not exists page_views_network_hash_created_idx
  on public.page_views (network_hash, created_at desc)
  where network_hash is not null;
create index if not exists leaderboard_score_user_idx
  on public.leaderboard (score desc, user_id);
create index if not exists score_transactions_created_idx
  on public.score_transactions (created_at desc);
create index if not exists score_transactions_user_created_idx
  on public.score_transactions (user_id, created_at desc);
create index if not exists score_transactions_action_created_idx
  on public.score_transactions (action, created_at desc);

alter table public.users enable row level security;
alter table public.page_views enable row level security;
alter table public.leaderboard enable row level security;
alter table public.score_transactions enable row level security;

-- Page-view tracking. Validated network hash counts unique networks instead of
-- raw IPs; the country header backfills the visitor's flag.
create or replace function public.track_page_view(
  p_visitor_id uuid,
  p_page_path text,
  p_referrer text,
  p_network_hash text,
  p_country_code text
)
returns boolean language plpgsql security definer set search_path = '' as $$
declare valid_country_code text;
begin
  valid_country_code := case
    when p_country_code ~ '^[A-Z]{2}$' and p_country_code <> 'XX' then p_country_code
    else null
  end;

  insert into public.users (id, display_name, country_code)
  values (p_visitor_id, 'Pixelify User', valid_country_code)
  on conflict (id) do update
    set country_code = coalesce(excluded.country_code, public.users.country_code);

  insert into public.page_views (visitor_id, user_id, page_path, referrer, network_hash)
  values (
    p_visitor_id,
    p_visitor_id,
    left(coalesce(p_page_path, '/'), 500),
    left(coalesce(p_referrer, ''), 1000),
    case when p_network_hash ~ '^[a-f0-9]{64}$' then p_network_hash else null end
  );

  return true;
end;
$$;

create or replace function public.get_public_stats()
returns jsonb language sql stable security definer set search_path = '' as $$
  select jsonb_build_object(
    'uniqueVisitors', (
      select count(distinct case
        when pv.network_hash is not null then 'ip:' || pv.network_hash
        else 'browser:' || pv.visitor_id::text
      end)
      from public.page_views pv
      where pv.network_hash is not null
        or not exists (
          select 1 from public.page_views known
          where known.visitor_id = pv.visitor_id and known.network_hash is not null
        )
    ),
    'pageViews', (select count(*) from public.page_views),
    'todayVisitors', (
      select count(distinct case
        when pv.network_hash is not null then 'ip:' || pv.network_hash
        else 'browser:' || pv.visitor_id::text
      end)
      from public.page_views pv
      where pv.created_at >= date_trunc('day', now() at time zone 'utc') at time zone 'utc'
        and (
          pv.network_hash is not null
          or not exists (
            select 1 from public.page_views known
            where known.visitor_id = pv.visitor_id
              and known.network_hash is not null
              and known.created_at >= date_trunc('day', now() at time zone 'utc') at time zone 'utc'
          )
        )
    ),
    'participants', (select count(*) from public.leaderboard where score > 0)
  );
$$;

-- Score transactions are the canonical successful-operation history, kept
-- idempotent per operation with an advisory lock and an hourly rate limit.
create or replace function public.award_operation_point(p_visitor_id uuid, p_operation_id uuid, p_action text)
returns boolean language plpgsql security definer set search_path = '' as $$
declare inserted_count integer;
begin
  if p_action not in ('background_removal', 'upscale') then raise exception 'Invalid score action'; end if;
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtext(p_visitor_id::text));
  if exists (select 1 from public.score_transactions where user_id = p_visitor_id and operation_id = p_operation_id) then
    return false;
  end if;
  if (select count(*) from public.score_transactions where user_id = p_visitor_id and created_at >= now() - interval '1 hour') >= 60 then
    raise exception 'Reward rate limit exceeded';
  end if;
  insert into public.users (id, display_name) values (p_visitor_id, 'Pixelify User') on conflict (id) do nothing;
  insert into public.score_transactions (user_id, operation_id, action, points)
  values (p_visitor_id, p_operation_id, p_action, 1) on conflict (user_id, operation_id) do nothing;
  get diagnostics inserted_count = row_count;
  if inserted_count = 0 then return false; end if;
  insert into public.leaderboard (user_id, score, updated_at) values (p_visitor_id, 1, now())
  on conflict (user_id) do update set score = public.leaderboard.score + 1, updated_at = now();
  return true;
end;
$$;

-- Single-argument all-time board; kept because the leaderboard API route uses
-- it as a fallback when the two-argument function is unavailable.
create or replace function public.get_leaderboard_data(p_visitor_id uuid default null)
returns jsonb language sql stable security definer set search_path = '' as $$
  with ranked as (
    select u.id, u.username, u.display_name, u.avatar_url, u.country_code, u.created_at, l.score,
      rank() over (order by l.score desc, u.created_at asc, u.id asc) as rank
    from public.leaderboard l join public.users u on u.id = l.user_id
    where l.score > 0
  )
  select jsonb_build_object(
    'top', coalesce((
      select jsonb_agg(to_jsonb(top_rows) order by top_rows.rank)
      from (select * from ranked order by score desc, created_at asc, id asc limit 101) top_rows
    ), '[]'::jsonb),
    'position', (select to_jsonb(r) from ranked r where r.id = p_visitor_id),
    'stats', public.get_public_stats()
  );
$$;

-- Two-argument board with week/month period rankings. Ranks tie-break on join
-- date (member since, oldest first) so every displayed rank stays unique.
create or replace function public.get_leaderboard_data(
  p_visitor_id uuid default null,
  p_period text default 'all'
)
returns jsonb language sql stable security definer set search_path = '' as $$
  with windowed as (
    select case p_period
      when 'week' then date_trunc('week', now())
      when 'month' then date_trunc('month', now())
      else '-infinity'::timestamptz
    end as starts_at
  ), scores as (
    select l.user_id, l.score::bigint as score
    from public.leaderboard l, windowed w
    where p_period = 'all' and l.score > 0
    union all
    select st.user_id, sum(st.points)::bigint as score
    from public.score_transactions st, windowed w
    where p_period in ('week', 'month') and st.created_at >= w.starts_at
    group by st.user_id
  ), ranked as (
    select u.id, u.username, u.display_name, u.avatar_url, u.country_code, u.created_at, s.score,
      rank() over (order by s.score desc, u.created_at asc, u.id asc) as rank
    from scores s join public.users u on u.id = s.user_id
    where s.score > 0
  ), participants as (
    select count(*)::bigint as count from public.leaderboard where score > 0
  )
  select jsonb_build_object(
    'top', coalesce((
      select jsonb_agg(to_jsonb(top_rows) order by top_rows.rank, top_rows.created_at asc, top_rows.id)
      from (select * from ranked order by score desc, created_at asc, id limit 101) top_rows
    ), '[]'::jsonb),
    'position', (select to_jsonb(r) from ranked r where r.id = p_visitor_id),
    'stats', jsonb_build_object('participants', (select count from participants))
  );
$$;

create or replace function public.get_activity_data(
  p_visitor_id uuid,
  p_type text default 'all',
  p_period text default 'all',
  p_limit integer default 20,
  p_offset integer default 0
)
returns jsonb language sql stable security definer set search_path = '' as $$
  with windowed as (
    select case p_period
      when 'today' then date_trunc('day', now())
      when 'week' then date_trunc('week', now())
      when 'month' then date_trunc('month', now())
      else '-infinity'::timestamptz
    end as starts_at
  ), all_activity as (
    select st.id, st.user_id as visitor_id, st.action, st.points, st.created_at
    from public.score_transactions st
    where st.user_id = p_visitor_id
  ), filtered as (
    select a.* from all_activity a, windowed w
    where a.created_at >= w.starts_at
      and (p_type = 'all' or (p_type = 'background_removal' and a.action = 'background_removal') or (p_type = 'upscale' and a.action = 'upscale'))
  ), summary as (
    select
      coalesce(sum(points), 0)::bigint as points,
      count(*)::bigint as total,
      count(*) filter (where action = 'background_removal')::bigint as backgrounds,
      count(*) filter (where action = 'upscale')::bigint as upscales
    from all_activity
  )
  select jsonb_build_object(
    'activities', coalesce((
      select jsonb_agg(to_jsonb(page_rows) order by page_rows.created_at desc, page_rows.id desc)
      from (select * from filtered order by created_at desc, id desc limit greatest(1, least(p_limit, 50)) offset greatest(0, p_offset)) page_rows
    ), '[]'::jsonb),
    'totalFiltered', (select count(*) from filtered),
    'summary', (select to_jsonb(summary) from summary)
  );
$$;

